# Bayesian Meta-Regression Analysis: Modulation of Carbon Anomalies (Z-Score)
# Expanded Predictors: CH, LAI, MAP, Fpar, MAT, Weighted_AWC, LATITUDE & All Combinations
#
# *** Version: Normal (Gaussian) Distribution - Heatwave (HW) Scenarios ***
#
# Analysis of three scenarios:
# 1. HW_ge_2: H >= 2 (Heatwave)
# 2. HW_ge_2_VPD_lt_2: H >= 2 & VPD < 2 (Pure Heatwave)
# 3. HW_ge_2_VPD_ge_2: H >= 2 & VPD >= 2 (Compound Heatwave & VPD)
#
# Key Features:
# - Dynamic Model Generation: All combinations of predictors (up to 4 vars)
# - Response Variable: mean_zscore (weighted by zscore_se)
# - Saves all brms model objects to .RData
#
# =============================================================================

library(tidyverse)
library(ggplot2)
library(brms)
library(patchwork)
library(posterior)
library(ggpmisc)
library(utils) # for combn

cat("========== Expanded Bayesian Meta-Regression Analysis (Gaussian, HW) ==========\n")
cat("Predictors: CH, LAI, MAP, Fpar, MAT, Weighted_AWC, LATITUDE\n")
cat("Strategy: Running combinations of variables (up to 4)\n\n")

# =============================================================================
# Section 0: Configuration
# =============================================================================
#
