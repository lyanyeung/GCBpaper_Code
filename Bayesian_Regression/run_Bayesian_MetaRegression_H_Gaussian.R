      theme(legend.position = "none", plot.title = element_text(size = 10))
    
    plots_list[[scenario_name]] <- p
  }
  
  final_p <- wrap_plots(plots_list, ncol = 3) + 
    plot_layout(guides = "collect") & theme(legend.position = "bottom")
  
  ggsave(file.path(CONFIG$output_dir, paste0(CONFIG$output_prefix, "_Scatter_", var_col, ".png")), 
         final_p, width = 12, height = 4.5, dpi = 300)
}

cat("Generating Forest Plot for Univariate Models...\n")

forest_data <- results_summary %>%
  filter(Num_Vars == 1) %>% 
  select(Scenario, Model_Label, matches("Beta_|Low_|Up_")) %>%
  pivot_longer(
    cols = matches("Beta_|Low_|Up_"),
    names_to = c("Stat", "Var"),
    names_pattern = "(Beta|Low|Up)_(.*)",
    values_to = "value"
  ) %>%
  filter(!is.na(value)) %>% 
  pivot_wider(names_from = Stat, values_from = value) %>%
  mutate(Var = gsub("_std", "", Var))

p_forest <- ggplot(forest_data, aes(x = Beta, y = Var, color = Scenario)) +
  geom_vline(xintercept = 0, linetype = "dashed", color = "gray60") +
  geom_point(position = position_dodge(width = 0.5), size = 3) +
  geom_errorbarh(aes(xmin = Low, xmax = Up),
                 position = position_dodge(width = 0.5), height = 0.2) +
  labs( 
    x = "Posterior mean standardized effect (β)", y = "Control") +
  theme_minimal() +
  scale_color_manual(values = c("#984EA3", "#FF7F00", "#4DAF4A"))

ggsave(file.path(CONFIG$output_dir, paste0(CONFIG$output_prefix, "_Forest_Univariate.png")), 
       p_forest, width = 8, height = 6, dpi = 300)

