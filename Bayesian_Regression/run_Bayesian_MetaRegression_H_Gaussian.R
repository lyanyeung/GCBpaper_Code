variables_to_plot <- list(
  list(col = "CH",   label = "Canopy Height (m)"),
  list(col = "LAI",  label = "Growing LAI"),
  list(col = "MAP",  label = "MAP (mm)"),
  list(col = "Fpar", label = "Fpar"),
